"""Generate exact native CQC world and actor registries."""

import argparse
from pathlib import Path

from .enemy_loot_profiles import PROFILES


def outputs():
    generator = "python -m tools.silverfish.generate_enemy_loot_registry"
    header = ["#pragma once", "", f"// Generated by {generator}", "",
              "#include <array>", "#include <String/StringType.hpp>", "",
              "namespace silverfish::enemy_loot_profiles", "{",
              "    struct Actor { const RC::CharType* world; const RC::CharType* path; };",
              "    inline constexpr std::array worlds{"]
    header.extend(f'        STR("{profile.world}"),' for profile in PROFILES)
    header.extend(("    };", "    inline constexpr std::array actors{"))
    lua = [f"-- Generated by {generator}", "local by_map = {}", "for _, row in ipairs({"]
    for index, profile in enumerate(PROFILES):
        for actor in profile.actors:
            header.append(f'        Actor{{worlds[{index}], STR("{actor.split(" ", 1)[1]}")}},')
        actors = ", ".join(f'"{actor}"' for actor in profile.actors)
        lua.append(f'    {{ "{profile.id}", "{profile.map}", "{profile.world}", "{profile.shell_prefix}", {{ {actors} }} }},')
    header.extend(("    };", "}", ""))
    lua.extend(("}) do", "    local id, area, world, raw_prefix, names = table.unpack(row)",
                "    local paths = {}",
                '    for _, name in ipairs(names) do paths[name] = name:match("^%S+ (.+)$") end',
                "    by_map[area] = { id = id, world = world, raw_prefix = raw_prefix, names = names, paths = paths }",
                "end", "return by_map", ""))
    return {"native/enemy_loot_registry.hpp": "\n".join(header),
            "mod/SilverfishCoop/Scripts/native_enemy_loot_registry.lua": "\n".join(lua)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    for relative, expected in outputs().items():
        path = root / relative
        if arguments.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"{relative} needs regeneration\n")
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
