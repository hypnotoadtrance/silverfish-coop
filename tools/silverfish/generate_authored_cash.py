"""Render the cooked loose cash placements as C++ and Lua source profiles."""

import argparse
import math
from pathlib import Path

from .authored_cash import CASH_TYPES, MAP_SLUGS, PLACEMENTS


def outputs() -> dict[str, str]:
    generator = "python -m tools.silverfish.generate_authored_cash"
    native = [f"// Generated by {generator}", ""]
    lua = [f"-- Generated by {generator}", "return {"]
    sources, paths, per_map = set(), set(), {}
    for row in sorted(PLACEMENTS, key=lambda placement: placement.path):
        count = per_map.get(row.area, 0) + 1
        if (row.area not in MAP_SLUGS or count > 32 or row.source in sources or row.path in paths
                or row.item not in CASH_TYPES or type(row.index) is not int or not 1 <= row.index <= 1024
                or len(row.position) != 3
                or not all(math.isfinite(value) and abs(value) <= 10_000_000 for value in row.position)
                or type(row.physics) is not bool):
            raise ValueError(f"Invalid cooked cash placement {row.path}")
        per_map[row.area] = count
        sources.add(row.source)
        paths.add(row.path)
        native.append(f'        Profile{{.source = "{row.source}", .world = STR("{row.world}"),')
        native.append(f'            .actor = STR("{row.path}"),')
        native.append(f'            .item_class = STR("{row.item.class_path}"),')
        native.append(f'            .x = {repr(row.position[0])}, .y = {repr(row.position[1])}, .z = {repr(row.position[2])},')
        native.append(f'            .item_type = 1, .physics = {str(row.physics).lower()}, .stock_cash = true}},')
        lua.append(f'    {{source = "{row.source}", map = "{row.area}",')
        lua.append(f'        path = "{row.path}",')
        lua.append(f'        class = "{row.item.class_path}", name = "{row.item.class_name}",')
        lua.append(f'        stock_cash = true, cash_min = {row.item.minimum}, cash_max = {row.item.maximum},')
        lua.append(f'        cash_flag = "{row.stock_flag}"}},')
    lua.extend(("}", ""))
    native.append("")
    return {
        "native/authored_cash_profiles.inc": "\n".join(native),
        "mod/SilverfishCoop/Scripts/authored_cash_catalog.lua": "\n".join(lua),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    for relative, expected in outputs().items():
        path = root / relative
        if arguments.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"{relative} needs regeneration\n")
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
