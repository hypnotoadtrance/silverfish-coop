"""Regenerate guest firearm profiles for the native and Lua adapters."""

import argparse
from pathlib import Path

from .guest_weapon_profiles import (
    AMMO_BY_KIND, BOLT_ACTION_UNLOAD_CAPACITY, BOLT_ACTION_UNLOADS, FIREARMS, HELD_FIRE_PROJECTILE_COUNTS,
    MAX_HELD_FIRE_ROUNDS, MAX_TAKE_AMMO_ROUNDS, NINE_MM_BALL, STOCK_AMMO, STOCK_HELD_FIRE_MAGAZINES,
)


def outputs() -> dict[str, str]:
    generator = "python -m tools.silverfish.generate_guest_weapon_registry"
    header = [
        "#pragma once", "",
        f"// Generated by {generator}", "",
        "#include <array>", "#include <string_view>", "#include <String/StringType.hpp>", "",
        "namespace silverfish::guest_weapon_profiles", "{",
        "    struct StockAmmo", "    {",
        "        int caliber;",
        "        const RC::CharType* row;",
        "        const RC::CharType* item;",
        "        const RC::CharType* projectile;",
        "        int fixture_units;",
        "        int projectile_count;",
        "    };", "",
    ]
    for ammo in STOCK_AMMO:
        header.append(f'    inline constexpr StockAmmo {ammo.symbol}{{{ammo.caliber}, STR("{ammo.row}"),')
        header.append(f'        STR("{ammo.item_path}"), STR("{ammo.projectile_path}"), '
                      f'{ammo.fixture_units}, {ammo.projectile_count}}};')
    header.append("    inline constexpr std::array stock_ammo{")
    for ammo in STOCK_AMMO:
        header.append(f"        &{ammo.symbol},")
    header.extend([
        "    };",
        "",
        "    struct Profile", "    {",
        "        std::string_view kind;",
        "        const RC::CharType* path;",
        "        bool headless_seed;",
        "        int capacity;",
        "        int burst_length;",
        "        double fire_rate;",
        "        bool require_default_payload;",
        "        const StockAmmo* ammo;",
        "        bool reload_first_stack;",
        "        bool action_on_release{};",
        "        const RC::CharType* underbarrel_mount{};",
        "    };", "",
        "    inline constexpr std::array firearms{",
    ])
    projectile_counts = ", ".join(f"[{count}] = true" for count in sorted(HELD_FIRE_PROJECTILE_COUNTS))
    lua = [
        f"-- Generated by {generator}",
        'local profiles = { paths = {}, kinds = {}, seeds = {}, ammo = {}, magazine_capacity = {}, held_fire = {}, underbarrel = {},',
        f'    max_take_ammo_rounds = {MAX_TAKE_AMMO_ROUNDS}, max_held_fire_rounds = {MAX_HELD_FIRE_ROUNDS},',
        f'    held_projectile_counts = {{ {projectile_counts} }},',
        f'    default_ammo = "{NINE_MM_BALL.item_path}" }}',
        "for _, row in ipairs({",
    ]
    for firearm in FIREARMS:
        magazine = firearm.magazine
        headless = str(firearm.headless_seed).lower()
        shape = (f"{magazine.capacity}, {magazine.burst_length}, {magazine.fire_rate}, "
                 f"{str(magazine.require_default_payload).lower()}, &{magazine.ammo.symbol}, "
                 f"{str(magazine.reload_first_stack).lower()}"
                 if magazine else "0, 0, 0.0, false, nullptr, false")
        if magazine and (magazine.action_on_release or firearm.underbarrel_mount):
            shape += f", {str(magazine.action_on_release).lower()}"
        if firearm.underbarrel_mount:
            shape += f', STR("{firearm.underbarrel_mount}")'
        ammo = f'"{magazine.ammo.item_path}"' if magazine and magazine.ammo != NINE_MM_BALL else "nil"
        lua_magazine = f", {ammo}, {magazine.capacity}" if magazine else ""
        header.append(f'        Profile{{"{firearm.kind}", STR("{firearm.path}"), {headless}, {shape}}},')
        lua.append(f'    {{ "{firearm.kind}", "{firearm.path}", {headless}{lua_magazine} }},')
    header.extend(("    };", "    inline constexpr std::array stock_held_fire_kinds{"))
    for kind in STOCK_HELD_FIRE_MAGAZINES:
        header.append(f'        std::string_view{{"{kind}"}},')
    header.extend((
        "    };",
        "    inline constexpr bool stock_held_fire(std::string_view kind)",
        "    {",
        "        for (auto candidate : stock_held_fire_kinds)",
        "            if (candidate == kind) return true;",
        "        return false;",
        "    }",
        f"    inline constexpr int bolt_action_magazine = {BOLT_ACTION_UNLOAD_CAPACITY};", "}", "",
    ))
    lua.extend((
        "}) do",
        "    local kind, path, headless, ammo, capacity = table.unpack(row, 1, 5)",
        "    profiles.paths[kind] = path",
        "    profiles.kinds[path] = kind",
        "    if headless then profiles.seeds[kind] = path end",
        "    profiles.ammo[kind] = ammo",
        "    profiles.magazine_capacity[path] = capacity",
        "end",
    ))
    for path in sorted(BOLT_ACTION_UNLOADS):
        lua.append(f'profiles.magazine_capacity["{path}"] = {BOLT_ACTION_UNLOAD_CAPACITY}')
    for kind in STOCK_HELD_FIRE_MAGAZINES:
        lua.append(f'profiles.held_fire["{kind}"] = true')
    for firearm in FIREARMS:
        if firearm.underbarrel_mount:
            lua.append(f'profiles.underbarrel["{firearm.kind}"] = "{firearm.underbarrel_mount}"')
    lua.append("profiles.ammo_options = {")
    for kind, options in AMMO_BY_KIND.items():
        if len(options) < 2:
            continue
        choices = ", ".join(f'["{path}"] = true' for path in sorted(options))
        lua.append(f'    ["{kind}"] = {{ {choices} }},')
    lua.extend(("}", "return profiles", ""))
    return {
        "native/guest_weapon_registry.hpp": "\n".join(header),
        "mod/SilverfishCoop/Scripts/guest_weapon_registry.lua": "\n".join(lua),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    repo = Path(__file__).resolve().parents[2]
    for relative, expected in outputs().items():
        path = repo / relative
        if arguments.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"{relative} needs regeneration\n")
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
