"""Render one cooked supply catalog as C++ profiles and Lua map metadata."""

import argparse
import math
from pathlib import Path
import re

from .authored_routes import MAPS
from .authored_supply import PLACEMENTS
from .guest_weapon_profiles import STOCK_AMMO


def outputs() -> dict[str, str]:
    generator = "python -m tools.silverfish.generate_authored_supply"
    native = [f"// Generated by {generator}", ""]
    lua = [f"-- Generated by {generator}", "return {"]
    sources, paths, per_map = set(), set(), {}
    for row in sorted(PLACEMENTS, key=lambda placement: placement.path):
        count = per_map.get(row.area, 0) + 1
        if (row.area not in MAPS or count > 32 or row.source in sources or row.path in paths or row.ammo not in STOCK_AMMO
                or not re.fullmatch(re.escape(row.ammo.item) + r"_C_\d+", row.name)
                or not all(math.isfinite(value) and abs(value) <= 10_000_000 for value in row.position)
                or type(row.physics) is not bool or type(row.units) is not int or not 1 <= row.units <= 1000
                or not math.isfinite(row.weight) or not 0 < row.weight <= 1000
                or type(row.value) is not int or not 1 <= row.value <= 100_000):
            raise ValueError(f"Invalid cooked supply placement {row.path}")
        per_map[row.area] = count
        sources.add(row.source)
        paths.add(row.path)
        xyz = ", ".join(map(repr, row.position))
        physics = str(row.physics).lower()
        native.append(f'        Profile{{"{row.source}", STR("{row.world}"), STR("{row.path}"),')
        native.append(f'            STR("{row.ammo.item_path}"), {xyz}, 8, {row.units}, {physics},')
        native.append(f'            &silverfish::guest_weapon_profiles::{row.ammo.symbol}, {row.weight}, {row.value}}},')
        lua.append(f'    {{source = "{row.source}", map = "{row.area}",')
        lua.append(f'        path = "{row.path}",')
        lua.append(f'        class = "{row.ammo.item_path}", name = "{row.ammo.item}_C", stock_supply = true}},')
    lua.extend(("}", ""))
    native.append("")
    return {
        "native/authored_supply_profiles.inc": "\n".join(native),
        "mod/SilverfishCoop/Scripts/authored_supply_catalog.lua": "\n".join(lua),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    for relative, expected in outputs().items():
        path = root / relative
        if arguments.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"{relative} needs regeneration\n")
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
